#!/usr/bin/env python3
"""Regenerates main/font_data.c from DejaVu Sans (free licence). Dev-time only."""
from PIL import Image, ImageDraw, ImageFont
D = "/usr/share/fonts/truetype/dejavu/"
FONTS = [
    ("sm",  D + "DejaVuSans.ttf",      10, 32, 126),
    ("smb", D + "DejaVuSans-Bold.ttf", 10, 32, 126),
    ("md",  D + "DejaVuSans-Bold.ttf", 13, 32, 126),
    ("lg",  D + "DejaVuSans-Bold.ttf", 20, 32, 126),
    ("xl",  D + "DejaVuSans-Bold.ttf", 52, 48, 58),
]
out = ['// Generated by tools/gen_fonts.py - do not edit.', '#include "font.h"', '']
for name, path, size, first, last in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    bmp, glyphs = bytearray(), []
    for code in range(first, last + 1):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            glyphs.append((len(bmp), 0, 0, 0, 0, adv)); continue
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        glyphs.append((len(bmp), w, h, l, asc + t, adv))
        bmp.extend(im.tobytes())
    out.append(f"static const uint8_t {name}_bmp[] = {{")
    for i in range(0, len(bmp), 24):
        out.append("    " + ",".join(str(v) for v in bmp[i:i+24]) + ",")
    out.append("};")
    out.append(f"static const glyph_t {name}_glyphs[] = {{")
    for g in glyphs:
        out.append("    {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"const font_t font_{name} = {{ {name}_glyphs, {name}_bmp, {first}, {last}, {asc+desc}, {asc} }};")
    out.append("")
    print(f"font_{name}: {size}px, line {asc+desc}, bitmap {len(bmp)} B")
open("main/font_data.c", "w").write("\n".join(out))
